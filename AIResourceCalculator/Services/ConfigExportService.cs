    public static string GetAzureVmSize(double cpu, double ram)
    {
        return (cpu, ram) switch
        {
            (<= 1, <= 2) => "Standard_B1s",
            (<= 2, <= 4) => "Standard_B2s",
            (<= 2, <= 8) => "Standard_D2s_v5",
            (<= 4, <= 16) => "Standard_D4s_v5",
            (<= 8, <= 32) => "Standard_D8s_v5",
            (<= 16, <= 64) => "Standard_D16s_v5",
            (<= 32, <= 128) => "Standard_D32s_v5",
            (<= 64, <= 256) => "Standard_F16s_v2",
            _ => "Standard_D32s_v5"
        };
    }

    public static string GetGcpMachineType(double cpu, double ram)
    {
        return (cpu, ram) switch
        {
            (<= 1, <= 4) => "e2-micro",
            (<= 2, <= 8) => "e2-small",
            (<= 4, <= 16) => "e2-medium",
            (<= 8, <= 32) => "e2-standard-8",
            (<= 16, <= 64) => "e2-standard-16",
            (<= 32, <= 128) => "e2-standard-32",
            _ => "e2-standard-8"
        };
    }

    public static string GetAwsInstanceType(double cpu, double ram)
    {
        return (cpu, ram) switch
        {
            (<= 1, <= 2) => "t3.nano",
            (<= 2, <= 4) => "t3.micro",
            (<= 2, <= 8) => "t3.small",
            (<= 4, <= 16) => "t3.medium",
            (<= 8, <= 32) => "m6i.large",
            (<= 16, <= 64) => "m6i.xlarge",
            (<= 32, <= 128) => "m6i.2xlarge",
            _ => "m6i.large"
        };
    }

    public static string SanitizeHtml(string input)
        => string.IsNullOrEmpty(input) ? "" : input.Replace("<", "&lt;").Replace(">", "&gt;").Replace("\"", "&quot;");
