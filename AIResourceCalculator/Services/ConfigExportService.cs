        var project = config.ProjectName.ToLower().Replace(" ", "-");
        var sb = new StringBuilder();

        // Chart.yaml
        sb.AppendLine("---");
        sb.AppendLine("# Chart.yaml");
        sb.AppendLine("apiVersion: v2");
        sb.AppendLine($"name: {project}");
        sb.AppendLine("description: Deployed by AI Resource Calculator");
        sb.AppendLine($"version: 0.1.0");
        sb.AppendLine($"appVersion: \"1.0\"");
        sb.AppendLine();
        sb.AppendLine("dependencies:");
        sb.AppendLine("  - name: common");
        sb.AppendLine("    version: \">=0.1.0\"");
        sb.AppendLine("    repository: \"https://charts.bitnami.com/bitnami\"");
        sb.AppendLine();
        sb.AppendLine("---");

        // values.yaml
        sb.AppendLine("# values.yaml");
        sb.AppendLine($"projectName: \"{config.ProjectName}\"");
        sb.AppendLine($"userCount: {config.UserCount}");
        sb.AppendLine($"deploymentType: \"{config.DeploymentType}\"");
        sb.AppendLine();
        sb.AppendLine("global:");
        sb.AppendLine("  environment: production");
        sb.AppendLine("  region: \"west-europe\"");
        sb.AppendLine();
        sb.AppendLine("image:");
        sb.AppendLine("  repository: \"myregistry.azurecr.io\"");
        sb.AppendLine("  pullPolicy: IfNotPresent");
        sb.AppendLine("  tag: \"latest\"");
        sb.AppendLine();
        sb.AppendLine("service:");
        sb.AppendLine("  type: ClusterIP");
        sb.AppendLine("  port: 80");
        sb.AppendLine();
        sb.AppendLine("ingress:");
        sb.AppendLine("  enabled: false");
        sb.AppendLine("  className: \"\"");
        sb.AppendLine("  hosts:");
        sb.AppendLine($"    - host: {project}.example.com");
        sb.AppendLine("      paths:");
        sb.AppendLine("        - path: /");
        sb.AppendLine("          pathType: Prefix");
        sb.AppendLine();

        var components = req.Components.Where(c => c.Cpu > 0).ToList();
        foreach (var component in components)
        {
            var name = component.Name.ToLower().Replace(" ", "-").Replace("(", "").Replace(")", "");
            sb.AppendLine($"{name}:");
            sb.AppendLine($"  replicaCount: {component.Replicas}");
            sb.AppendLine($"  image:");
            sb.AppendLine($"    repository: \"{name}\"");
            sb.AppendLine($"    tag: \"latest\"");
            sb.AppendLine($"  resources:");
            sb.AppendLine($"    requests:");
            sb.AppendLine($"      cpu: \"{component.Cpu:F1}\"");
            sb.AppendLine($"      memory: \"{component.RamGb}Gi\"");
            sb.AppendLine($"    limits:");
            sb.AppendLine($"      cpu: \"{component.Cpu:F1}\"");
            sb.AppendLine($"      memory: \"{component.RamGb}Gi\"");
            sb.AppendLine($"  service:");
            sb.AppendLine($"    port: 8080");
            sb.AppendLine($"    targetPort: 8080");
            sb.AppendLine();
        }

        sb.AppendLine("---");

        // templates/_helpers.tpl
        sb.AppendLine("{{/* _helpers.tpl */}}");
        sb.AppendLine("{{- define \"{project}.name\" -}}");
        sb.AppendLine("{{- default .Chart.Name .Values.nameOverride | trunc 63 | trimSuffix \"-\" }}");
        sb.AppendLine("{{- end }}");
        sb.AppendLine();
        sb.AppendLine("{{- define \"{project}.fullname\" -}}");
        sb.AppendLine("{{- if .Values.fullnameOverride }}");
        sb.AppendLine("{{- .Values.fullnameOverride | trunc 63 | trimSuffix \"-\" }}");
        sb.AppendLine("{{- else }}");
        sb.AppendLine("{{- $name := default .Chart.Name .Values.nameOverride }}");
        sb.AppendLine("{{- if contains $name .Release.Name }}");
        sb.AppendLine("{{- .Release.Name | trunc 63 | trimSuffix \"-\" }}");
        sb.AppendLine("{{- else }}");
        sb.AppendLine("{{- printf \"%s-%s\" .Release.Name $name | trunc 63 | trimSuffix \"-\" }}");
        sb.AppendLine("{{- end }}");
        sb.AppendLine("{{- end }}");
        sb.AppendLine("{{- end }}");
        sb.AppendLine();
        sb.AppendLine("---");

        // templates/deployment.yaml
        foreach (var component in components)
        {
            var name = component.Name.ToLower().Replace(" ", "-").Replace("(", "").Replace(")", "");
            sb.AppendLine("---");
            sb.AppendLine($"# templates/deployment-{name}.yaml");
            sb.AppendLine("apiVersion: apps/v1");
            sb.AppendLine("kind: Deployment");
            sb.AppendLine("metadata:");
            sb.AppendLine($"  name: {{ include \"{project}.fullname\" . }}-{name}");
            sb.AppendLine("  labels:");
            sb.AppendLine($"    app.kubernetes.io/name: {name}");
            sb.AppendLine("    app.kubernetes.io/instance: {{ .Release.Name }}");
            sb.AppendLine("spec:");
            sb.AppendLine($"  replicas: {{ .Values.{name}.replicaCount }}");
            sb.AppendLine("  selector:");
            sb.AppendLine("    matchLabels:");
            sb.AppendLine($"      app.kubernetes.io/name: {name}");
            sb.AppendLine("  template:");
            sb.AppendLine("    metadata:");
            sb.AppendLine("      labels:");
            sb.AppendLine($"        app.kubernetes.io/name: {name}");
            sb.AppendLine("    spec:");
            sb.AppendLine("      containers:");
            sb.AppendLine($"        - name: {name}");
            sb.AppendLine($"          image: \"{{ .Values.{name}.image.repository }}:{{ .Values.{name}.image.tag }}\"");
            sb.AppendLine("          imagePullPolicy: {{ .Values.image.pullPolicy }}");
            sb.AppendLine("          ports:");
            sb.AppendLine("            - containerPort: {{ .Values.{name}.service.targetPort }}");
            sb.AppendLine("          resources:");
            sb.AppendLine("            {{- toYaml .Values.{name}.resources | nindent 12 }}");
        }

        sb.AppendLine("---");

        // templates/service.yaml
        foreach (var component in components)
        {
            var name = component.Name.ToLower().Replace(" ", "-").Replace("(", "").Replace(")", "");
            sb.AppendLine("---");
            sb.AppendLine($"# templates/service-{name}.yaml");
            sb.AppendLine("apiVersion: v1");
            sb.AppendLine("kind: Service");
            sb.AppendLine("metadata:");
            sb.AppendLine($"  name: {{ include \"{project}.fullname\" . }}-{name}");
            sb.AppendLine("  labels:");
            sb.AppendLine($"    app.kubernetes.io/name: {name}");
            sb.AppendLine("spec:");
            sb.AppendLine("  type: {{ .Values.service.type }}");
            sb.AppendLine("  ports:");
            sb.AppendLine("    - port: {{ .Values.service.port }}");
            sb.AppendLine("      targetPort: {{ .Values.{name}.service.targetPort }}");
            sb.AppendLine("      protocol: TCP");
            sb.AppendLine("      name: http");
            sb.AppendLine("  selector:");
            sb.AppendLine($"    app.kubernetes.io/name: {name}");
        }

        return sb.ToString();
    }

    public string ExportGcpTerraform(ResourceRequirement req, ProjectConfig config)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by AI Resource Calculator");
        sb.AppendLine("# Google Cloud Platform (GCP) Terraform");
        sb.AppendLine($"# Project: {config.ProjectName}, Users: {config.UserCount}");
        sb.AppendLine();
        sb.AppendLine("provider \"google\" {");
        sb.AppendLine("  project = var.project_id");
        sb.AppendLine("  region  = var.region");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("variable \"project_id\" {");
        sb.AppendLine($"  default = \"{GcpProjectId}\"");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("variable \"region\" {");
        sb.AppendLine($"  default = \"{GcpRegion}\"");
        sb.AppendLine("}");

        foreach (var infra in req.Infrastructure)
        {
            var name = infra.Name.ToLower().Replace(" ", "-").Replace("(", "").Replace(")", "");
            var machineType = GetGcpMachineType(infra.Cpu, infra.RamGb);
            sb.AppendLine($"resource \"google_compute_instance\" \"{name}\" {{");
            sb.AppendLine($"  name         = \"vm-{name}\"");
            sb.AppendLine("  machine_type = machine_type");
            sb.AppendLine("  zone         = \"${var.region}-a\"");
            sb.AppendLine();
            sb.AppendLine("  boot_disk {");
            sb.AppendLine("    initialize_params {");
            sb.AppendLine("      image = \"ubuntu-os-cloud/ubuntu-2404-lts-amd64\"");
            sb.AppendLine("      size  = 50");
            sb.AppendLine("    }");
            sb.AppendLine("  }");
            sb.AppendLine();
            sb.AppendLine("  network_interface {");
            sb.AppendLine("    network = \"default\"");
            sb.AppendLine("  }");
            sb.AppendLine($"  count = {infra.NodeCount}");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

